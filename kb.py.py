def normalize(text: str) -> str:
    """ตัดช่องว่าง เครื่องหมาย และคำฟุ่มเฟือย เหลือเฉพาะแกนความหมาย"""
    t = text.lower().strip()
    t = re.sub(r"[^\u0E00-\u0E7Fa-z0-9]+", "", t)
    for w in _STOPWORDS:
        t = t.replace(w, "")
    return t


def _bigrams(s: str) -> set:
    return {s[i:i + 2] for i in range(len(s) - 1)}


def dice(a: str, b: str) -> float:
    """Sørensen–Dice coefficient บน bigram ทนต่อการพิมพ์ผิดเล็กน้อย"""
    A, B = _bigrams(a), _bigrams(b)
    if not A or not B:
        return 0.0
    return 2 * len(A & B) / (len(A) + len(B))


def check_emergency(text: str) -> bool:
    n = normalize(text)
    return any(normalize(p) in n for p in EMERGENCY_PATTERNS)


def match(question: str, threshold: float = 0.16):
    """
    คืนค่า (entry, score) โดยรวมคะแนน 2 แบบ
      1) จำนวนคำสำคัญที่ปรากฏในคำถาม (ให้น้ำหนักสูง)
      2) ความคล้ายกับตัวอย่างคำถามและชื่อหัวข้อ
    """
    q = normalize(question)
    if len(q) < 2:
        return None, 0.0

    best, best_score = None, 0.0
    for item in KB:
        kw_hits = sum(1 for k in item["kw"] if normalize(k) and normalize(k) in q)
        kw_score = min(kw_hits, 3) * 0.30

        sim = max([dice(q, normalize(s)) for s in item["q"] + [item["topic"]]] or [0])
        total = kw_score + sim * 0.55

        if total > best_score:
            best, best_score = item, total

    return (best, best_score) if best_score >= threshold else (None, best_score)


